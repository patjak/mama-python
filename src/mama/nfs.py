from __future__ import annotations

import ipaddress
import os
import pathlib
import subprocess
from typing import Dict, List

import config
from logger import debug, error, fatal, out


class NfsManager:
    """Manages NFS server export configuration and systemd service on openSUSE."""

    @classmethod
    def get_network(cls) -> str:
        """Calculate network CIDR for clients controlled by dnsmasq."""
        if hasattr(config, "NFS_SUBNET") and config.NFS_SUBNET:
            return config.NFS_SUBNET

        host = getattr(config, "MAMA_HOST", "192.168.2.1")
        netmask = getattr(config, "DHCP_NETMASK", "255.255.255.0")
        try:
            net = ipaddress.IPv4Network(f"{host}/{netmask}", strict=False)
            return str(net)
        except Exception as e:
            debug(f"[NFS] Failed to calculate network from host/netmask: {e}")
            return f"{host}/{netmask}"

    @classmethod
    def generate_config(cls) -> str:
        """Generate NFS export configuration serving MAMA_PATH directly."""
        # Use raw configured path without .resolve() to preserve symlink /usr/share/mama
        mama_path = str(getattr(config, "MAMA_PATH", "/usr/share/mama")).rstrip("/")
        network = cls.get_network()
        options = getattr(
            config,
            "NFS_OPTIONS",
            "rw,sync,no_root_squash,no_subtree_check,fsid=0,crossmnt,insecure",
        )

        lines: List[str] = [
            "# Automatically generated by MAMA. Do not edit managed sections manually.",
            f"# Serves {mama_path} to all clients on dnsmasq network ({network})",
            f"{mama_path} {network}({options})",
            "",
        ]
        return "\n".join(lines)

    @classmethod
    def write_config(cls) -> bool:
        """Write generated export configuration to disk."""
        conf_path = pathlib.Path(
            getattr(config, "NFS_EXPORTS_PATH", "/etc/exports.d/mama.exports")
        )
        content = cls.generate_config()

        try:
            conf_path.parent.mkdir(parents=True, exist_ok=True)
            conf_path.write_text(content, encoding="utf-8")
            os.chmod(conf_path, 0o644)
            debug(f"[NFS] Wrote export configuration to {conf_path}")
            return True
        except PermissionError:
            error(f"[NFS] Permission denied writing to {conf_path}. Run with sudo or root.")
            return False
        except Exception as e:
            error(f"[NFS] Failed writing NFS configuration: {e}")
            return False

    @classmethod
    def is_active(cls) -> bool:
        """Check if nfs-server systemd service is active."""
        service = getattr(config, "NFS_SERVICE_NAME", "nfs-server")
        res = subprocess.run(["systemctl", "is-active", "--quiet", service])
        return res.returncode == 0

    @classmethod
    def reload_or_restart(cls) -> bool:
        """Write export configuration, re-export paths with exportfs, and ensure nfs-server is running."""
        if not getattr(config, "NFS_ENABLED", True):
            return True

        if not cls.write_config():
            return False

        service = getattr(config, "NFS_SERVICE_NAME", "nfs-server")

        res_export = subprocess.run(["exportfs", "-ra"], capture_output=True, text=True)
        if res_export.returncode != 0:
            error(f"[NFS] exportfs -ra failed: {res_export.stderr.strip()}")

        if cls.is_active():
            res = subprocess.run(["systemctl", "reload-or-restart", service])
            if res.returncode == 0:
                out(f"[NFS] Reloaded {service} service and refreshed exports.")
                return True
        else:
            res = subprocess.run(["systemctl", "restart", service])
            if res.returncode == 0:
                out(f"[NFS] Started {service} service.")
                return True

        error(f"[NFS] Failed to reload/restart {service}. Check `journalctl -u {service}`.")
        return False

    @classmethod
    def get_active_exports(cls) -> List[Dict[str, str]]:
        """Get list of active export entries, normalizing canonical paths to MAMA_PATH."""
        exports: List[Dict[str, str]] = []
        configured_path = str(getattr(config, "MAMA_PATH", "/usr/share/mama")).rstrip("/")
        try:
            real_configured = str(pathlib.Path(configured_path).resolve())
        except Exception:
            real_configured = configured_path

        def normalize_path(p: str) -> str:
            # Display MAMA_PATH if the underlying export points to the same target
            if p == real_configured:
                return configured_path
            return p

        try:
            res = subprocess.run(["exportfs", "-v"], capture_output=True, text=True)
            if res.returncode == 0 and res.stdout.strip():
                for line in res.stdout.splitlines():
                    line = line.strip()
                    if not line or line.startswith("#"):
                        continue
                    parts = line.split()
                    if len(parts) >= 2:
                        raw_path = parts[0]
                        rest = " ".join(parts[1:])
                        if "(" in rest and rest.endswith(")"):
                            client, opts = rest.split("(", 1)
                            opts = opts.rstrip(")")
                        else:
                            client, opts = rest, ""
                        exports.append({
                            "path": normalize_path(raw_path),
                            "client": client,
                            "options": opts,
                        })
                return exports
        except Exception:
            pass

        etab = pathlib.Path("/var/lib/nfs/etab")
        if etab.exists():
            try:
                for line in etab.read_text(encoding="utf-8").splitlines():
                    line = line.strip()
                    if not line or line.startswith("#"):
                        continue
                    parts = line.split()
                    if len(parts) >= 2:
                        raw_path = parts[0]
                        rest = " ".join(parts[1:])
                        if "(" in rest and rest.endswith(")"):
                            client, opts = rest.split("(", 1)
                            opts = opts.rstrip(")")
                        else:
                            client, opts = rest, ""
                        exports.append({
                            "path": normalize_path(raw_path),
                            "client": client,
                            "options": opts,
                        })
            except Exception as e:
                debug(f"[NFS] Failed to read /var/lib/nfs/etab: {e}")

        return exports