from __future__ import annotations

import os
import pathlib
import subprocess
from typing import Dict, List, Optional, Set

import config
from logger import debug, error, fatal, out
from machine import to_bool
from repository import MachineRepository


class DnsmasqManager:
    """Manages dnsmasq configuration (DHCP + TFTP), autoexec.ipxe, and systemd service on openSUSE."""

    @classmethod
    def generate_autoexec_ipxe(cls) -> bool:
        """Create or update autoexec.ipxe in the TFTP directory without an inner DHCP loop."""
        mama_base = pathlib.Path(getattr(config, "MAMA_PATH", "/usr/share/mama")).resolve()
        tftp_dir = pathlib.Path(getattr(config, "TFTP_DIR", mama_base / "tftp")).resolve()
        port = int(os.environ.get("PORT", 8080))
        server_ip = os.environ.get("BIND_ADDR", getattr(config, "MAMA_HOST", "192.168.2.1"))
        http_host = f"{server_ip}:{port}" if str(port) != "80" else server_ip

        try:
            tftp_dir.mkdir(parents=True, exist_ok=True)
            autoexec_path = tftp_dir / "autoexec.ipxe"
            content = (
                "#!ipxe\n"
                f"chain http://{http_host}/boot.py?mac=${{mac}} || shell\n"
            )
            autoexec_path.write_text(content, encoding="utf-8")
            os.chmod(autoexec_path, 0o644)
            debug(f"[DHCP] Generated {autoexec_path} pointing to http://{http_host}")
            return True
        except Exception as e:
            error(f"[DHCP] Failed to generate autoexec.ipxe: {e}")
            return False

    @classmethod
    def get_existing_custom_hosts(cls, managed_macs: Set[str]) -> List[str]:
        """Extract manually added dhcp-host entries from the existing config file."""
        conf_path = pathlib.Path(getattr(config, "DNSMASQ_CONF_PATH", "/etc/dnsmasq.d/mama.conf"))
        if not conf_path.exists():
            return []

        custom_entries: List[str] = []
        try:
            for line in conf_path.read_text(encoding="utf-8").splitlines():
                stripped = line.strip()
                if stripped.startswith("dhcp-host="):
                    entry_data = stripped[len("dhcp-host=") :]
                    parts = [p.strip().lower() for p in entry_data.split(",") if p.strip()]
                    if parts:
                        mac = parts[0]
                        if mac not in managed_macs:
                            custom_entries.append(stripped)
        except Exception as e:
            debug(f"[DHCP] Failed to parse existing custom host entries: {e}")

        return custom_entries

    @classmethod
    def generate_config(cls) -> str:
        """Generate dnsmasq configuration tailored for MAMA DHCP, TFTP, and static leases."""
        tftp_root = getattr(config, "TFTP_DIR", f"{config.MAMA_PATH}/tftp")

        lines: List[str] = [
            "# Automatically generated by MAMA. Do not edit managed sections manually.",
            f"interface={getattr(config, 'DHCP_INTERFACE', 'br0')}",
            "bind-interfaces",
            "# Disable DNS functionality to avoid port 53 conflicts",
            "port=0",
            "# Log DHCP queries and tags to systemd journal for debugging",
            "log-dhcp",
            "",
            "# DHCP Scope",
            (
                f"dhcp-range={config.DHCP_RANGE_START},{config.DHCP_RANGE_END},"
                f"{config.DHCP_NETMASK},{config.DHCP_LEASE_TIME}"
            ),
            f"dhcp-option=option:router,{config.MAMA_HOST}",
            f"dhcp-option=option:dns-server,{config.MAMA_HOST}",
            f"dhcp-option=option:server-ip-address,{config.MAMA_HOST}",
            "",
            "# Built-in TFTP Server for firmware binaries and iPXE scripts",
            "enable-tftp",
            f"tftp-root={tftp_root}",
            "",
            "# Match iPXE via Option 77 (User-Class) or Option 175",
            "dhcp-userclass=set:ipxe,iPXE",
            "dhcp-match=set:ipxe,175",
            "",
            "# Match Client Architectures (Option 93)",
            "dhcp-match=set:bios,option:client-arch,0",
            "dhcp-match=set:efi-x86,option:client-arch,6",
            "dhcp-match=set:efi-x86_64,option:client-arch,7",
            "dhcp-match=set:efi-x86_64,option:client-arch,9",
            "dhcp-match=set:efi-arm64,option:client-arch,11",
            "",
            "# Boolean logic: Set boot tag ONLY if client is NOT running iPXE",
            "tag-if=set:boot-bios,tag:bios,tag:!ipxe",
            "tag-if=set:boot-efi-x86,tag:efi-x86,tag:!ipxe",
            "tag-if=set:boot-efi-x86_64,tag:efi-x86_64,tag:!ipxe",
            "tag-if=set:boot-efi-arm64,tag:efi-arm64,tag:!ipxe",
            "",
            "# Native Firmware Boot Files (served via dnsmasq TFTP to initial PXE client)",
            f"dhcp-boot=tag:boot-bios,undionly.kpxe,,{config.MAMA_HOST}",
            f"dhcp-boot=tag:boot-efi-x86,ipxe.efi,,{config.MAMA_HOST}",
            f"dhcp-boot=tag:boot-efi-x86_64,ipxe.efi,,{config.MAMA_HOST}",
            f"dhcp-boot=tag:boot-efi-arm64,ipxe-arm64.efi,,{config.MAMA_HOST}",
            "",
            "# iPXE Boot Script: served via TFTP to break UEFI Option 67 loops",
            f"dhcp-boot=tag:ipxe,autoexec.ipxe,,{config.MAMA_HOST}",
            "",
            "# ==========================================================================",
            "# Registered Machines (MAMA Managed Leases & Hostnames)",
            "# ==========================================================================",
        ]

        managed_macs: Set[str] = set()
        machines = MachineRepository.get_all()
        for m in machines:
            mac = m.get("mac", "").strip().lower()
            name = m.get("name", "").strip()
            ip = m.get("ip", "").strip()

            if not mac:
                continue

            managed_macs.add(mac)

            if ip and name:
                lines.append(f"dhcp-host={mac},{ip},{name}")
            elif ip:
                lines.append(f"dhcp-host={mac},{ip}")
            elif name:
                lines.append(f"dhcp-host={mac},{name}")
            else:
                lines.append(f"dhcp-host={mac}")

        custom_hosts = cls.get_existing_custom_hosts(managed_macs)
        if custom_hosts:
            lines.append("")
            lines.append("# ==========================================================================")
            lines.append("# Custom / External Static Assignments (Preserved across syncs)")
            lines.append("# ==========================================================================")
            for entry in custom_hosts:
                lines.append(entry)

        lines.append("")
        return "\n".join(lines)

    @classmethod
    def write_config(cls) -> bool:
        """Write generated configuration and autoexec.ipxe."""
        cls.generate_autoexec_ipxe()

        conf_path = pathlib.Path(getattr(config, "DNSMASQ_CONF_PATH", "/etc/dnsmasq.d/mama.conf"))
        content = cls.generate_config()

        try:
            conf_path.parent.mkdir(parents=True, exist_ok=True)
            conf_path.write_text(content, encoding="utf-8")
            os.chmod(conf_path, 0o644)
            debug(f"[DHCP] Wrote configuration to {conf_path}")
            return True
        except PermissionError:
            error(f"[DHCP] Permission denied writing to {conf_path}. Run with sudo or root.")
            return False
        except Exception as e:
            error(f"[DHCP] Failed writing dnsmasq configuration: {e}")
            return False

    @classmethod
    def test_syntax(cls) -> bool:
        """Validate dnsmasq configuration syntax."""
        conf_path = getattr(config, "DNSMASQ_CONF_PATH", "/etc/dnsmasq.d/mama.conf")
        res = subprocess.run(
            f"dnsmasq --test -C {conf_path}",
            shell=True,
            capture_output=True,
            text=True,
        )
        if res.returncode != 0:
            error(f"[DHCP] dnsmasq syntax test failed: {res.stderr.strip()}")
            return False
        return True

    @classmethod
    def reload_or_restart(cls) -> bool:
        """Ensure config is valid and fully restart dnsmasq."""
        if not getattr(config, "DHCP_ENABLED", True):
            return True

        if not cls.write_config():
            return False

        if not cls.test_syntax():
            return False

        res = subprocess.run("systemctl restart dnsmasq", shell=True)
        if res.returncode == 0:
            out("[DHCP] Restarted dnsmasq service.")
            return True
        error("[DHCP] Failed to restart dnsmasq. Check `journalctl -u dnsmasq`.")
        return False

    @classmethod
    def get_active_leases(cls) -> Dict[str, str]:
        """Parse dnsmasq lease database into a MAC -> IP lookup dictionary."""
        lease_file = pathlib.Path(
            getattr(config, "DNSMASQ_LEASES_FILE", "/var/lib/misc/dnsmasq.leases")
        )
        if not lease_file.exists():
            fallback = pathlib.Path("/var/lib/dnsmasq/dnsmasq.leases")
            if fallback.exists():
                lease_file = fallback
            else:
                return {}

        leases: Dict[str, str] = {}
        try:
            for line in lease_file.read_text(encoding="utf-8").splitlines():
                parts = line.strip().split()
                if len(parts) >= 3:
                    mac = parts[1].strip().lower()
                    ip = parts[2].strip()
                    leases[mac] = ip
        except Exception as e:
            debug(f"[DHCP] Could not read leases file: {e}")

        return leases

    @classmethod
    def sync_leases_to_db(cls) -> None:
        """Update any started machines lacking an IP in SQLite using active lease data."""
        leases = cls.get_active_leases()
        if not leases:
            return

        for m_data in MachineRepository.get_all():
            mac = m_data.get("mac", "").lower()
            current_ip = m_data.get("ip", "")
            raw_started = m_data.get("is_started") if "is_started" in m_data else m_data.get("_is_started", False)
            is_started = to_bool(raw_started)

            # Only auto-assign lease IP if the machine is actively marked as started
            if mac in leases and not current_ip and is_started:
                assigned_ip = leases[mac]
                MachineRepository.update_fields(
                    m_data["name"],
                    {"ip": assigned_ip, "state": "dhcp-bound"},
                )
                debug(f"[DHCP] Auto-discovered IP {assigned_ip} for {m_data['name']} from DHCP lease")